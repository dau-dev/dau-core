"""Polars-free validation of the OHLCV golden fixtures.

Recomputes bars from the prepared-trades fixture with pure Python and compares
against the exported bars, so hardware-facing tests can rely on these files
without a polars dependency. Fixtures are generated by
``python -m dau_polars.ohlcv_fixtures`` (see dau-docs-private/OHLCV_BARS.md).
"""

from __future__ import annotations

import csv
from pathlib import Path

import pytest

FIXTURE_DIR = Path(__file__).parent / "fixtures" / "ohlcv"


def _read(name: str) -> list[dict[str, str]]:
    with open(FIXTURE_DIR / name, newline="") as handle:
        return list(csv.DictReader(handle))


def _compute_bars(prepared: list[dict[str, str]]) -> dict[tuple[str, int, int], dict[str, int]]:
    bars: dict[tuple[str, int, int], dict] = {}
    for row in prepared:
        key = (row["symbol"], int(row["symbol_id"]), int(row["bucket"]))
        price = int(row["price_micro"])
        size = int(row["size_micro"])
        order = (float(row["TIME_M"]), float(row["TR_SEQNUM"]))
        bar = bars.get(key)
        if bar is None:
            bars[key] = {
                "open": price,
                "high": price,
                "low": price,
                "close": price,
                "volume": size,
                "trades": 1,
                "_open_key": order,
                "_close_key": order,
            }
            continue
        bar["high"] = max(bar["high"], price)
        bar["low"] = min(bar["low"], price)
        bar["volume"] += size
        bar["trades"] += 1
        if order < bar["_open_key"]:
            bar["open"], bar["_open_key"] = price, order
        if order >= bar["_close_key"]:
            bar["close"], bar["_close_key"] = price, order
    return bars


@pytest.mark.parametrize("session", ["regular", "full"])
def test_exported_bars_match_pure_python_recomputation(session: str) -> None:
    prepared = _read(f"prepared_{session}.csv")
    expected = _compute_bars(prepared)
    exported = _read(f"bars_{session}.csv")

    assert len(exported) == len(expected)
    for row in exported:
        key = (row["symbol"], int(row["symbol_id"]), int(row["bucket"]))
        bar = expected[key]
        for field in ("open", "high", "low", "close", "volume", "trades"):
            assert int(row[field]) == bar[field], f"{key} {field}"


@pytest.mark.parametrize("session", ["regular", "full"])
def test_bar_invariants(session: str) -> None:
    for row in _read(f"bars_{session}.csv"):
        high, low = int(row["high"]), int(row["low"])
        assert high >= low
        assert low <= int(row["open"]) <= high
        assert low <= int(row["close"]) <= high
        assert int(row["trades"]) >= 1


def test_prepared_fixture_is_sorted_per_host_guarantee() -> None:
    prepared = _read("prepared_regular.csv")
    keys = [(int(r["symbol_id"]), int(r["bucket"]), float(r["TIME_M"]), float(r["TR_SEQNUM"])) for r in prepared]
    assert keys == sorted(keys)
