"""Generated cores go through the same seams as checked-in ones.

A tile whose HDL is rendered is the first thing in this registry that has no
file beside its entry. That is a place where a parallel mechanism could
easily grow -- a build-layer side channel that renders somewhere the registry
cannot see. The rule against it is the one already learned the hard way: a
tile known only to the build layer never reaches ``core_names``, so its HDL
goes unstaged, its spec hash collides with its siblings, and its resources
go unpriced.

So: the generator is reached through the registry, its parameters are hydra
configuration like every other fact, and the rendered file arrives at
``source_path()`` -- the same accessor dependency closure and synthesis
already use.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from hydra.utils import instantiate

from dau_core.cores import CoreDefinition, UnrenderedCoreError
from dau_core.exp_generator import ExpTileGenerator
from dau_core.fixed_point import EXP_EXACT, EXP_LIGHT

_BASE = {
    "name": "generated-probe",
    "kind": "operator",
    "module": "dau_fixed_point_exp",
    "source": "dau_fixed_point_exp.sv",
    "description": "a generated core used to pin the rendering contract",
    "contract_kind": "row-stream",
    "record_words": 2,
    "ingest": {"rows": 1, "per_cycles": 3},
}


def _definition(**overrides) -> CoreDefinition:
    return CoreDefinition(**{**_BASE, **overrides})


def test_a_generated_core_refuses_its_source_until_rendered(tmp_path: Path, monkeypatch) -> None:
    """Rendering implicitly on read would hide which parameters produced the
    file that then gets synthesized.

    Points the render root at an empty directory: the session fixture renders
    the real palette, and without this isolation that fixture would satisfy
    the very refusal under test.
    """
    monkeypatch.setenv("DAU_CORE_RENDER_ROOT", str(tmp_path / "empty"))
    core = _definition(generator=ExpTileGenerator(datapath=EXP_EXACT))
    with pytest.raises(UnrenderedCoreError, match="render-cores"):
        core.source_path()


def test_rendering_writes_the_source_the_entry_names(tmp_path: Path) -> None:
    core = _definition(generator=ExpTileGenerator(datapath=EXP_EXACT))
    written = core.render(into=tmp_path)
    assert written.name == core.source, "the rendered file must be the one the registry entry names"
    assert written.read_text(encoding="utf-8").startswith("`default_nettype none")


def test_a_checked_in_core_refuses_to_be_rendered() -> None:
    """The inverse mistake: rendering over a hand-written tile would replace
    reviewed HDL with generated text."""
    core = _definition(source="dau_row_map_alu.sv")
    with pytest.raises(ValueError, match="not generated"):
        core.render()


def test_the_operating_point_comes_from_configuration(tmp_path: Path) -> None:
    """The parameters are hydra-injected, not Python literals — the same rule
    the rest of the registry follows. Instantiating from a config tree is the
    thing that must work, so it is what is tested."""
    config = {
        "_target_": "dau_core.cores.CoreDefinition",
        **_BASE,
        "generator": {
            "_target_": "dau_core.exp_generator.ExpTileGenerator",
            "datapath": {
                "_target_": "dau_core.fixed_point.ExpDatapath",
                "internal_bits": 36,
                "table_bits": 8,
                "degree": 3,
                "round_steps": True,
            },
        },
    }
    core = instantiate(config, _convert_="all")
    assert core.generator.datapath == EXP_LIGHT, "the configured operating point must survive instantiation"

    rendered = core.generator.render()
    assert rendered.parameters["INTERNAL_BITS"] == 36
    assert rendered.parameters["DEGREE"] == 3
    assert rendered.parameters["ROUND_STEPS"] == 1


def test_each_operating_point_renders_a_different_source() -> None:
    """Two points must not render identical HDL, or the spec hash could not
    tell them apart and one measurement would be quoted for both."""
    exact = ExpTileGenerator(datapath=EXP_EXACT).render()
    light = ExpTileGenerator(datapath=EXP_LIGHT).render()
    assert exact.text != light.text
    assert exact.parameters != light.parameters


def test_the_rendered_source_carries_the_parameters_that_made_it() -> None:
    """A generated file with no record of its inputs is untraceable back to
    the configuration that produced it."""
    rendered = ExpTileGenerator(datapath=EXP_EXACT).render()
    assert "GENERATED by" in rendered.text
    assert "do not edit" in rendered.text
    for value in ("INTERNAL_BITS = 52", "TABLE_BITS = 8", "DEGREE = 4"):
        assert value in rendered.text, f"the rendered source does not state {value}"
